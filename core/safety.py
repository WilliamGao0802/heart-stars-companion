"""极端内容安全处置（与 packages/core/src/safety.js 逐字同源）。

设计原则：
  极端内容（自杀/自残方式与计划、极端言论）不走正常对话流程：
    ① 立刻停止本轮 AI 生成，只显示固定安全回应（SAFE_REPLY）；
    ② 该条内容不入本地历史、不上云 —— 相当于「删除该条日记」；
    ③ 必须把账号信息 + 内容上报 admin_alerts 云表（管理员端可见），保护用户安全。
  检测是纯函数：词表命中即触发，不交给模型判断（安全判断永远在本地）。
"""

# ================= 一、极端词表 =================
# 比 companion 的 crisis 情绪词更重一层：包含方式、计划与行为描述。
EXTREME_WORDS = [
    # 直接表达
    "自杀", "自残", "想死", "不想活", "活不下去", "死了算了", "结束生命", "结束一切",
    "了结自己", "没有活下去", "活着没意思", "让我死", "希望我死",
    # 方式与行为描述
    "跳楼", "跳桥", "跳河", "跳下去", "上吊", "割腕", "烧炭", "吞安眠药", "吃安眠药",
    "安眠药配酒", "站在天台", "天台上", "写遗书", "遗书", "买了药准备", "准备离开这个世界",
]


# ================= 二、检测 =================
def detect_extreme(text):
    """返回 {"extreme": bool, "words": [str]}。空/非字符串输入一律安全。"""
    t = str(text or "")
    if not t:
        return {"extreme": False, "words": []}
    words = [w for w in EXTREME_WORDS if w in t]
    return {"extreme": len(words) > 0, "words": words}


# ================= 三、固定安全回应 =================
# 极端内容触发后唯一会显示的文字。温柔、有存在感，绝不冷漠、不说教；
# 必须给出即时求助路径（这是唯一允许「直接给热线」的情形——安全永远第一）。
SAFE_REPLY = (
    "先别动，好吗？我就在这儿，哪儿也不去。\n"
    "你愿意把这句话说出来，我已经听见了，这不是小事，我很在意。\n"
    "如果你现在离危险很近，请一定马上告诉身边能碰到的任何一个人——家人、老师、朋友都行；\n"
    "也可以立刻拨打 12356（24 小时都有人接，免费、匿名），紧急情况直接拨 120。\n"
    "等你回来，想说什么我都听着。你不需要一个人扛着。"
)


# ================= 四、上报构造 =================
def build_alert(source, user_id, text, words):
    """source: 'h5' | 'mp' | 'app' | 'st'；user_id 取不到时用 'anonymous'（仍上报，不漏报）。"""
    return {
        "user_id": str(user_id or "anonymous")[:64],
        "source": str(source or "")[:8],
        "content": str(text or "")[:500],
        "words": ",".join(words or [])[:200],
    }
