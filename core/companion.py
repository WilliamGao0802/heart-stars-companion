def pick_starters(now_ms=None):
    """每次从全量里随机挑 5 个（「不知道从哪说起」永远保留——它是说不出话的人的出口）。"""
    fixed = STARTERS_ALL[-2]  # '不知道从哪说起'
    pool = [s for s in STARTERS_ALL if s != fixed]
    picked = [fixed]

    now_ms = now_ms if now_ms else _now_ms()
    seed = now_ms // (24 * 60 * 60 * 1000)  # 按天轮换，同一天不闪变

    def rnd(n):
        nonlocal seed
        seed = (seed * 9301 + 49297) % 233280
        return int(seed / 233280 * n)

    rest = pool[:]
    while len(picked) < 5 and rest:
        picked.append(rest.pop(rnd(len(rest))))
    return picked


