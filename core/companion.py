def reply_to(text, state, now_ms=None):
    """本地规则版回复（无 AI 时的兜底，也是小程序路线 B 的口径）。
    返回要显示的一条或多条消息（不含 id，由页面补）。"""
    now_ms = now_ms if now_ms else _now_ms()
    normalize_state(state, now_ms)

    a = analyze(text)
    state["turns"] += 1

    if a["level"] >= 1:
        state["negativeStreak"] += 1
    elif a["mood"] == "good":
        state["negativeStreak"] = 0
    else:
        state["negativeStreak"] = max(0, state["negativeStreak"] - 1)

    for n in a["topics"]:
        state["topics"][n] = state["topics"].get(n, 0) + 1

    out = []

    # ① 危机信号：最高优先级
    if a["mood"] == "crisis":
        if state["turns"] - state["crisisShownAtTurn"] >= 2:
            state["crisisShownAtTurn"] = state["turns"]
            out.append({"role": "care", "kind": "crisis", "title": "先停一下，好吗",
                        "text": CRISIS_TEXT, "hotline": True})
            return out

    # ② 普通回复：情绪池轮换
    mood = "heavy" if a["mood"] == "crisis" else a["mood"]
    bank = BANKS.get(mood) or BANKS["neutral"]
    idx = state["bankIndex"].get(mood, 0)
    state["bankIndex"][mood] = idx + 1

    parts = [bank[idx % len(bank)]]

    # ③ 同一个话题被再次提到
    rep = _repeat_topic(state, a["topics"])
    if rep:
        parts.append(_topic_line(rep["name"], rep["count"], state["topicLineIndex"]))
        state["topicLineIndex"] += 1

    # ④ 情绪一路往下沉，就点破它
    if a["level"] >= 1 and state["negativeStreak"] >= 3:
        parts.append(DEEP[state["deepIndex"] % len(DEEP)])
        state["deepIndex"] += 1

    out.append({"role": "ai", "text": "\n\n".join(parts)})

    # ⑤ 到点了就轻轻把你拉回现实
    care = _care_for(state, now_ms)
    if care:
        card = _care_card(care)
        out.append({"role": "care", "kind": card["kind"], "title": card["title"],
                    "text": card["text"], "hotline": False})

    return out


