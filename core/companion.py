# ================= 七、组装回复（多轮感知，本地规则版） =================
def _topic_line(name, count, idx):
    if count >= 3:
        return "「" + name + "」这件事，你今天已经提过 " + str(count) + " 次了。"
    lines = [
        "关于「" + name + "」，你是第二次提到它了。",
        "我留意到，「" + name + "」又出现了。",
    ]
    return lines[idx % len(lines)]


def _repeat_topic(state, current_topics):
    name = ""
    count = 0
    for n in current_topics:
        c = state["topics"].get(n, 0)
        if c > count:
            count = c
            name = n
    if name and count >= 2:
        return {"name": name, "count": count}
    return None


def _care_for(state, now_ms):
    h = datetime.fromtimestamp(now_ms / 1000, tz=timezone(timedelta(hours=8))).hour
    late_night = h >= 23 or h < 5
    long_talk = state["turns"] >= 12
    if not late_night and not long_talk:
        return None
    if late_night and state["turns"] < 4:
        return None
    if state["turns"] - state["lastCareAtTurn"] < 10:
        return None
    state["lastCareAtTurn"] = state["turns"]
    return "night" if late_night else "long"


